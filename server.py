#!/usr/bin/env python3
"""Lifeboat web UI. Standard library only (plus `anthropic` for the Claude step).

    python server.py            # http://localhost:8000
    LOG_PATH=/path/to/logs.jsonl python server.py
"""
import json
import os
import re
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from lifeboat.notify import post_slack
from lifeboat.pipeline import ROOT, Run

RUN = Run()
LOG_PATH = os.environ.get("LOG_PATH", os.path.join(ROOT, "data", "logs.jsonl"))
PORT = int(os.environ.get("PORT", "8000"))


APPR_RE = re.compile(r"^\s*(waiting for (your )?approval|approval pending|awaiting approval|needs approval|pending approval)\s*[:\-–]?\s*", re.I)
DONE_RE = re.compile(r"^\s*(already )?done( by lifeboat)?( \(reversible\))?\s*[:\-–]?\s*", re.I)


def slack_text(report: dict, status: dict | None = None) -> str:
    status = status or {}
    lines = [f":rotating_light: *[{report.get('severity', '').upper()}] {report.get('headline', '')}*"]
    if report.get("containment_summary"):
        lines.append(report["containment_summary"])
    live = status.get("live") or {}
    if live.get("actions"):
        lines.append("\n*Done by Lifeboat (reversible):*")
        lines += [f"- {a['label']}" for a in live["actions"]]
    appr = status.get("approvals", [])
    done = [a for a in appr if a["status"] == "approved"]
    pend = [a for a in appr if a["status"] != "approved"]
    if done:
        lines.append("\n*Approved by a human:*")
        lines += [f"- :white_check_mark: {a['action']}" for a in done]
    if pend:
        lines.append("\n*Still waiting for approval:*")
        lines += [f"- {a['action']}" for a in pend]
    creds = sorted(report.get("credentials_to_rotate", []), key=lambda c: c.get("priority", 99))
    if creds:
        lines.append("\n*Credentials to rotate:*")
        lines += [f"{c.get('priority')}. `{c.get('credential_id')}`: {c.get('why_exposed')}" for c in creds]
    other = [st for st in sorted(report.get("containment_steps", []), key=lambda x: x.get("order", 99))
             if not APPR_RE.match(st.get("step", "")) and not DONE_RE.match(st.get("step", ""))]
    if other:
        lines.append("\n*Other next steps:*")
        lines += [f"- {st.get('step')}" for st in other[:6]]
    lines.append("\n_Generated by Lifeboat. Raw logs never left our infrastructure._")
    return "\n".join(lines)


class H(BaseHTTPRequestHandler):
    def _json(self, obj, code=200):
        body = json.dumps(obj, default=str).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *a):
        pass

    def do_GET(self):
        if self.path in ("/", "/index.html"):
            with open(os.path.join(ROOT, "static", "index.html"), "rb") as f:
                body = f.read()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
        elif self.path == "/api/status":
            self._json(RUN.snapshot())
        elif self.path == "/api/egress":
            self._json(RUN.snapshot(include_egress=True).get("egress_log", []))
        else:
            self._json({"error": "not found"}, 404)

    def do_POST(self):
        if self.path == "/api/run":
            ok = RUN.start(LOG_PATH)
            self._json({"started": ok})
        elif self.path.startswith("/api/live"):
            protect = "protect=0" not in self.path
            self._json({"started": RUN.start_live(protect)})
        elif self.path.startswith("/api/approve/"):
            RUN.approve(self.path.rsplit("/", 1)[-1])
            self._json({"ok": True})
        elif self.path == "/api/notify":
            report = RUN.snapshot().get("report")
            if not report:
                return self._json({"error": "no report yet"}, 400)
            text = slack_text(report, RUN.snapshot())
            ok, note = post_slack(text)
            self._json({"sent": ok, "preview": text, "note": None if ok else note})
        else:
            self._json({"error": "not found"}, 404)


if __name__ == "__main__":
    import threading
    from lifeboat import local_llm
    threading.Thread(target=local_llm.warmup, daemon=True).start()
    print(f"Lifeboat on http://localhost:{PORT}  (logs: {LOG_PATH})")
    print(f"Pre-loading local model {local_llm.LOCAL_MODEL} in the background...")
    ThreadingHTTPServer(("0.0.0.0", PORT), H).serve_forever()
